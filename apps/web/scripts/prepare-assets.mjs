// Copies runtime assets into public/ and generates build-time data modules.
//  - public/wasm/{web-tree-sitter,tree-sitter-cpp}.wasm  (parser worker)
//  - public/monaco/vs/**                                  (Monaco AMD build served locally — no CDN)
//  - public/blockly-media/**                              (Blockly media served locally — no CDN)
//  - src/generated/templates.ts                           (from ../../examples + ./templates)
//  - src/generated/parser-coverage.ts                     (docs/parser-coverage.md, if present)
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, "..");
const root = path.resolve(web, "..", "..");
const reqParser = createRequire(path.join(root, "packages", "cpp-parser", "package.json"));

mkdirSync(path.join(web, "public", "wasm"), { recursive: true });
cpSync(reqParser.resolve("web-tree-sitter/web-tree-sitter.wasm"), path.join(web, "public", "wasm", "web-tree-sitter.wasm"));
cpSync(path.join(path.dirname(reqParser.resolve("tree-sitter-cpp/package.json")), "tree-sitter-cpp.wasm"), path.join(web, "public", "wasm", "tree-sitter-cpp.wasm"));

const monacoMin = path.join(web, "node_modules", "monaco-editor", "min", "vs");
const monacoDest = path.join(web, "public", "monaco", "vs");
if (!existsSync(path.join(monacoDest, "loader.js"))) cpSync(monacoMin, monacoDest, { recursive: true });

// Blockly media (dropdown arrows, quote glyphs, cursors) served from our origin, never a CDN.
const blocklyMedia = path.join(web, "node_modules", "blockly", "media");
const blocklyDest = path.join(web, "public", "blockly-media");
if (existsSync(blocklyMedia)) cpSync(blocklyMedia, blocklyDest, { recursive: true });

const META = {
  "dht11-esp32": { title: "DHT11 on ESP32", category: "Sensors", board: "esp32:esp32:esp32", deps: [{ name: "DHT sensor library" }, { name: "Adafruit Unified Sensor" }], description: "Read temperature and humidity every 2 s and print them to Serial, skipping failed reads." },
  "dht11-esp32-nonblocking": { title: "DHT11 non-blocking (millis)", category: "Sensors", board: "esp32:esp32:esp32", deps: [{ name: "DHT sensor library" }, { name: "Adafruit Unified Sensor" }], description: "Same sensor, timed with millis() so loop() never blocks — the pattern for multitasking sketches." },
  "blink-uno": { title: "Blink (Uno)", category: "LED", board: "arduino:avr:uno", deps: [], description: "The classic: toggle the built-in LED once per second." },
  "button-led": { title: "Button + LED", category: "Input", board: "arduino:avr:uno", deps: [], description: "Light an LED while a push button (INPUT_PULLUP) is pressed." },
  "pwm-fade": { title: "PWM fade", category: "LED", board: "arduino:avr:uno", deps: [], description: "Fade an LED up and down with analogWrite on a PWM pin." },
  "servo-sweep": { title: "Servo sweep", category: "Motion", board: "arduino:avr:uno", deps: [{ name: "Servo" }], description: "Sweep a hobby servo from 0° to 180° and back." },
  "serial-monitor": { title: "Serial monitor", category: "Serial", board: "arduino:avr:uno", deps: [], description: "Print an analog reading and uptime to the Serial Monitor twice a second." },
};
const sources = [];
for (const dir of [path.join(root, "examples"), path.join(web, "templates")]) {
  if (!existsSync(dir)) continue;
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) {
      const ino = readdirSync(p).find((f) => f.endsWith(".ino"));
      if (ino) sources.push({ id: name, content: readFileSync(path.join(p, ino), "utf8"), origin: path.relative(root, path.join(p, ino)) });
    } else if (name.endsWith(".ino")) {
      sources.push({ id: name.replace(/\.ino$/, ""), content: readFileSync(p, "utf8"), origin: path.relative(root, p) });
    }
  }
}
const seen = new Set();
const out = [];
for (const s of sources) {
  if (seen.has(s.id) || !META[s.id]) continue;
  seen.add(s.id);
  const m = META[s.id];
  out.push({ id: s.id, title: m.title, category: m.category, boardFqbn: m.board, description: m.description, dependencies: m.deps, origin: s.origin, files: [{ path: `${s.id.replace(/[^a-zA-Z0-9_]/g, "_")}.ino`, content: s.content }] });
}
out.sort((a, b) => Object.keys(META).indexOf(a.id) - Object.keys(META).indexOf(b.id));
mkdirSync(path.join(web, "src", "generated"), { recursive: true });
writeFileSync(path.join(web, "src", "generated", "templates.ts"),
  `// GENERATED by scripts/prepare-assets.mjs — do not edit.\nimport type { TemplateDef } from "@/lib/templates-types";\nexport const TEMPLATES: TemplateDef[] = ${JSON.stringify(out, null, 2)};\n`);
const cov = path.join(root, "docs", "parser-coverage.md");
writeFileSync(path.join(web, "src", "generated", "parser-coverage.ts"),
  `// GENERATED by scripts/prepare-assets.mjs — do not edit.\nexport const PARSER_COVERAGE_MD: string | null = ${existsSync(cov) ? JSON.stringify(readFileSync(cov, "utf8")) : "null"};\n`);
console.log(`prepare-assets: wasm + monaco ready, ${out.length} templates, coverage doc ${existsSync(cov) ? "found" : "missing"}`);
