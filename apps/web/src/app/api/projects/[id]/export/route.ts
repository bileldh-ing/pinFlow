import JSZip from "jszip";
import { z } from "zod";
import { repos } from "@/server/db";
import { route } from "@/server/http";

type Ctx = { params: Promise<{ id: string }> };

function safeName(s: string) { return s.replace(/[^A-Za-z0-9_-]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 60) || "sketch"; }

/** Export the latest saved revision as .ino or as an Arduino-CLI-compatible sketch folder ZIP. */
export const GET = route<Ctx>(async (req, user, ctx) => {
  const { id } = await ctx.params;
  z.string().uuid().parse(id);
  const format = new URL(req.url).searchParams.get("format") === "ino" ? "ino" : "zip";
  const r = await repos();
  const p = await r.projects.get(user.id, id);
  const files = await r.projects.files(user.id, id);
  const deps = await r.projects.dependencies(user.id, id);
  const name = safeName(p.title);
  if (format === "ino") {
    const main = files.find((f) => f.path.endsWith(".ino")) ?? files[0]!;
    return new Response(main.content, { headers: { "content-type": "text/plain; charset=utf-8", "content-disposition": `attachment; filename="${name}.ino"`, "cache-control": "no-store" } });
  }
  const zip = new JSZip();
  const folder = zip.folder(name)!;
  // Arduino CLI requires the main .ino to match the folder name.
  const inos = files.filter((f) => f.path.endsWith(".ino"));
  for (const f of files) folder.file(f === inos[0] ? `${name}.ino` : f.path, f.content);
  folder.file("sketch.yaml", `# Generated by PinFlow Studio\ndefault_fqbn: ${p.boardFqbn}\n`);
  folder.file("pinflow.json", JSON.stringify({ format: "pinflow-project@1", title: p.title, boardFqbn: p.boardFqbn, revision: p.activeRevision, dependencies: deps.map((d) => ({ name: d.name, version: d.version, kind: d.kind })) }, null, 2));
  const buf = await zip.generateAsync({ type: "uint8array" });
  return new Response(buf as unknown as BodyInit, { headers: { "content-type": "application/zip", "content-disposition": `attachment; filename="${name}.zip"`, "cache-control": "no-store" } });
});
